// Regenerate src/capacity.generated.ts: how many of each plan's GPU our GCP
// project may run in each of our regions (its GPU quota: on-demand for a plan,
// Spot, i.e. PREEMPTIBLE_*, for the Spot plans named after their GPU, and
// on-demand for the "-ondemand" plans). The API
// offers a plan only where this is above zero, and tries regions with quota
// to spare first (src/regions.ts, byAvailability). Run it when GCP grants or
// changes quota, or when adding a region or a plan:
//
//   node scripts/gcp-quotas.mjs <gcp-project>
//
// Needs `gcloud` signed in. Reads quota only; changes nothing. T4, L4 and
// A100 quota is per region (NVIDIA_*_GPUS); H100 and newer GPUs are under
// GPUS_PER_GPU_FAMILY in the Cloud Quotas API.
// Keep REGIONS in step with src/regions.ts, and PLANS with src/pricing.ts.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const REGIONS = ["us-central1", "us-east1", "us-west1", "europe-west4", "asia-southeast1", "asia-east1"];
// Each plan's GPU, by regional metric and by GPU family (whichever GCP uses).
// Spot GPUs count against their own PREEMPTIBLE_* regional quota, except
// where spotInFamily says GCP counts them under the family quota.
const GPUS = {
  t4: { metric: "NVIDIA_T4_GPUS", family: "NVIDIA_T4" },
  l4: { metric: "NVIDIA_L4_GPUS", family: "NVIDIA_L4" },
  a100: { metric: "NVIDIA_A100_GPUS", family: "NVIDIA_A100" },
  // No regional metric: GCP counts it only under the RTX PRO 6000 family quota,
  // Spot and on-demand alike.
  rtx6000: { metric: "NVIDIA_RTX_PRO_6000_GPUS", family: "NVIDIA_RTX_PRO_6000", spotInFamily: true },
};
const PLANS = {
  ...Object.fromEntries(
    Object.entries(GPUS).map(([id, g]) => [id, { metric: `PREEMPTIBLE_${g.metric}`, family: g.spotInFamily ? g.family : "" }]),
  ),
  ...Object.fromEntries(Object.entries(GPUS).map(([id, g]) => [`${id}-ondemand`, { metric: g.metric, family: g.family }])),
  // Not offered yet (no quota), kept for when GCP grants it.
  "a100-80-ondemand": { metric: "NVIDIA_A100_80GB_GPUS", family: "NVIDIA_A100_80GB" },
  // Spot-only; GCP counts it under the H100 family quota. Not offered in
  // Taiwan, though we have quota there: Iowa, the Netherlands and Singapore
  // are cheaper and nearer most users.
  h100: { metric: "NVIDIA_H100_GPUS", family: "NVIDIA_H100", skipRegions: ["asia-east1"] },
};

const project = process.argv[2];
if (!project) {
  console.error("usage: node scripts/gcp-quotas.mjs <gcp-project>");
  process.exit(1);
}
const gcloud = (...args) => execFileSync("gcloud", args, { encoding: "utf8" });

// Regional metrics, one region at a time.
const regional = {};
for (const region of REGIONS) {
  const r = JSON.parse(gcloud("compute", "regions", "describe", region, "--project", project, "--format=json"));
  regional[region] = Object.fromEntries(r.quotas.map((q) => [q.metric, Number(q.limit)]));
}

// GPU-family quota (Cloud Quotas API), per region where it's set.
const token = gcloud("auth", "print-access-token").trim();
const res = await fetch(
  `https://cloudquotas.googleapis.com/v1/projects/${project}/locations/global/services/compute.googleapis.com/quotaInfos/GPUS-PER-GPU-FAMILY-per-project-region`,
  { headers: { authorization: `Bearer ${token}`, "x-goog-user-project": project } },
);
if (!res.ok) throw new Error(`Cloud Quotas API: HTTP ${res.status} ${await res.text()}`);
const family = {};
for (const d of (await res.json()).dimensionsInfos ?? []) {
  const { region, gpu_family: fam } = d.dimensions ?? {};
  if (region && fam) (family[fam] ??= {})[region] = Number(d.details?.value ?? 0);
}

const capacity = {};
for (const [plan, { metric, family: fam, skipRegions = [] }] of Object.entries(PLANS)) {
  capacity[plan] = {};
  for (const region of REGIONS) {
    if (skipRegions.includes(region)) {
      capacity[plan][region] = 0;
      continue;
    }
    // The larger of the two: GCP keeps the old metric for some GPUs and the
    // family quota for others, and leaves the other at 0.
    capacity[plan][region] = Math.max(regional[region][metric] ?? 0, (fam && family[fam]?.[region]) || 0);
  }
  console.log(plan, JSON.stringify(capacity[plan]));
}

writeFileSync(
  new URL("../src/capacity.generated.ts", import.meta.url),
  `// Generated by scripts/gcp-quotas.mjs from GCP GPU quota (Spot quota for Spot plans); do not edit.
// GPUs of each plan our project may run per region (0: not offered there).
export const PLAN_CAPACITY: Record<string, Record<string, number>> = ${JSON.stringify(capacity, null, 2)};
`,
);

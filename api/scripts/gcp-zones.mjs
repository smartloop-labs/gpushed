#!/usr/bin/env node
// Regenerate src/zones.generated.ts: for each plan, the zones in each of our
// regions that offer its machine type (and its GPU, when one is attached).
// The API hands these to the provisioner, which then tries zones without
// listing every machine type in every zone first (~30 s per box). Run it
// when adding a region or a plan, or now and then to pick up new zones:
//
//   node scripts/gcp-zones.mjs <gcp-project>
//
// Needs `gcloud` signed in. A zone that stops offering a plan is skipped by
// the provisioner, so a stale table costs a few seconds, never a failed box.

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

// Keep in step with REGIONS in scripts/gcp-prices.mjs and src/regions.ts.
const REGIONS = ["us-central1", "us-east1", "us-west1", "europe-west4", "asia-southeast1", "asia-east1"];

// Machine type and attached GPU ("" when built in) of each plan. Keep in
// step with PLANS in src/pricing.ts.
const PLANS = {
  t4: { machineType: "n1-standard-8", gpuType: "nvidia-tesla-t4" },
  l4: { machineType: "g2-standard-4", gpuType: "" },
  a100: { machineType: "a2-highgpu-1g", gpuType: "" },
  "a100-80": { machineType: "a2-ultragpu-1g", gpuType: "" },
  h100: { machineType: "a3-highgpu-1g", gpuType: "" },
  rtx6000: { machineType: "g4-standard-48", gpuType: "" },
};

const project = process.argv[2];
if (!project) {
  console.error("usage: node scripts/gcp-zones.mjs <gcp-project>");
  process.exit(2);
}

function zonesOffering(kind, name) {
  const out = execFileSync(
    "gcloud",
    ["compute", kind, "list", `--project=${project}`, `--filter=name=${name}`, "--format=value(zone.basename())"],
    { encoding: "utf8" },
  );
  return new Set(out.split("\n").filter(Boolean));
}

const result = {};
for (const [id, plan] of Object.entries(PLANS)) {
  let zones = zonesOffering("machine-types", plan.machineType);
  if (plan.gpuType) {
    const gpu = zonesOffering("accelerator-types", plan.gpuType);
    zones = new Set([...zones].filter((z) => gpu.has(z)));
  }
  result[id] = {};
  for (const region of REGIONS) {
    result[id][region] = [...zones].filter((z) => z.replace(/-[a-z0-9]+$/, "") === region).sort();
  }
  console.error(`${id}: ${Object.values(result[id]).flat().length} zones`);
}

const date = new Date().toISOString().slice(0, 10);
writeFileSync(
  new URL("../src/zones.generated.ts", import.meta.url),
  `// Generated by scripts/gcp-zones.mjs on ${date}. Do not edit by hand.
// Zones in each region offering each plan's machine type (and GPU).

export const PLAN_ZONES: Record<string, Record<string, string[]>> = ${JSON.stringify(result, null, 2)};
`,
);
